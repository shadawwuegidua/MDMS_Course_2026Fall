    def test_concurrent_draft_clear_cannot_publish_an_empty_survey(self):
        survey_id = self.create()

        def normalize_then_clear(raw_questions):
            canonical = normalize_questions(raw_questions)
            # Real MongoDB update simulates another tab saving an empty draft
            # between publish-time validation and the final atomic update.
            changed = self.db.surveys.update_one(
                {"_id": ObjectId(survey_id), "status": "draft"},
                {"$set": {"questions": []}},
            )
            self.assertEqual(changed.matched_count, 1)
            return canonical

        with patch("app.normalize_questions", side_effect=normalize_then_clear) as hook:
            result = self.api(self.owner, "POST", f"/api/surveys/{survey_id}/publish", {})
        hook.assert_called_once()
        self.assertEqual(result.status_code, 409, result.get_data(as_text=True))
        stored = self.db.surveys.find_one({"_id": ObjectId(survey_id)})
        self.assertEqual(stored["status"], "draft")
        self.assertEqual(stored["questions"], [])
        self.assertEqual(self.writer.get(f"/api/public/surveys/{survey_id}").status_code, 409)
        self.assertEqual(self.submit(survey_id, {"q1": "opt_a"}).status_code, 409)
        self.assertEqual(self.db.responses.count_documents({"survey_id": ObjectId(survey_id)}), 0)

