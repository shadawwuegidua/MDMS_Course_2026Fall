    def concurrent_submissions(self, allow_multiple, count=5):
        survey_id = self.create(allow_multiple=allow_multiple)
        self.publish(survey_id)
        clients = []
        for _ in range(count):
            client = self.app.test_client()
            result = client.post("/login", data={
                "username": self.writer_name, "password": PASSWORD,
                "csrf_token": self.csrf(client),
            })
            self.assertEqual(result.status_code, 302)
            clients.append((client, self.csrf(client)))
        barrier = Barrier(count)

        def send(item):
            client, token = item
            barrier.wait(timeout=10)
            result = client.post(f"/api/surveys/{survey_id}/responses", json={"answers": {"q1": "opt_a"}},
                                 headers={"X-CSRF-Token": token})
            return result.status_code

        with ThreadPoolExecutor(max_workers=count) as executor:
            statuses = list(executor.map(send, clients))
        return survey_id, statuses

