def question(qid="q1", kind="single", required=True, **overrides):
    item = {
        "id": qid, "title": "测试题目 " + qid, "type": kind,
        "required": required,
        "options": ([{"id": "opt_a", "text": "选项甲"},
                     {"id": "opt_b", "text": "选项乙"}]
                    if kind in ("single", "multiple") else []),
        "validation": {}, "rules": [],
    }
    item.update(overrides)
    return item


class SurveyIntegrationTests(unittest.TestCase):
    """Use independent accounts and surveys for every test, never user data."""

    @classmethod
    def setUpClass(cls):
        cls.database_name = "survey_stage1_tests_" + uuid4().hex
        cls.app = create_app({
            "TESTING": True,
            "MONGO_DB": cls.database_name,
            "SECRET_KEY": "integration-test-only-secret",
        })
        cls.db = cls.app.extensions["db"]
        if cls.db.name != cls.database_name:
            raise RuntimeError("Refusing to test against an unexpected database")

    @classmethod
    def tearDownClass(cls):
        client = cls.app.extensions["mongo_client"]
        try:
            expected = cls.database_name
            if (cls.db.name != expected
                    or not expected.startswith("survey_stage1_tests_")
                    or len(expected.removeprefix("survey_stage1_tests_")) != 32):
                raise RuntimeError("Refusing to remove an unexpected database")
            client.drop_database(expected)
        finally:
            client.close()

    def setUp(self):
        self.owner, self.owner_name = self.registered_client("owner")
        self.writer, self.writer_name = self.registered_client("writer")

    def csrf(self, client):
        response = client.get("/api/session")
        self.assertEqual(response.status_code, 200)
        return response.get_json()["csrf_token"]

    def registered_client(self, prefix):
        client = self.app.test_client()
        name = prefix + "_" + uuid4().hex[:14]
        response = client.post("/register", data={
            "username": name, "password": PASSWORD,
            "csrf_token": self.csrf(client),
        })
        self.assertEqual(response.status_code, 302, response.get_data(as_text=True))
        session = client.get("/api/session").get_json()
        self.assertEqual(session["user"]["username"], name)
        return client, name

    def api(self, client, method, path, payload=None):
        return client.open(
            path, method=method, json=payload,
            headers={"X-CSRF-Token": self.csrf(client)},
        )

    def create(self, questions=None, **settings):
        payload = {
            "title": "集成测试问卷", "description": "真实 MongoDB 集成测试",
            "is_anonymous": False, "allow_multiple": False,
            "deadline": None, "questions": questions if questions is not None else [question()],
        }
        payload.update(settings)
        result = self.api(self.owner, "POST", "/api/surveys", payload)
        self.assertEqual(result.status_code, 201, result.get_data(as_text=True))
        return result.get_json()["id"]

    def publish(self, survey_id):
        result = self.api(self.owner, "POST", f"/api/surveys/{survey_id}/publish", {})
        self.assertEqual(result.status_code, 200, result.get_data(as_text=True))

    def submit(self, survey_id, answers, client=None):
        return self.api(client or self.writer, "POST",
                        f"/api/surveys/{survey_id}/responses", {"answers": answers})

    def stats(self, survey_id, suffix=""):
        result = self.owner.get(f"/api/surveys/{survey_id}/statistics{suffix}")
        self.assertEqual(result.status_code, 200, result.get_data(as_text=True))
        return result.get_json()

